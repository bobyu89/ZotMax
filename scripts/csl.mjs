// Builds content/styles/apa-7-zh-tw*.csl: Zotero's official APA 7 style (CC BY-SA 3.0) plus Chinese layouts
// (CSL-M `layout locale="zh"`) for items whose language is zh / zh-TW, so the Zotero Word plugin writes Chinese
// references in Taiwanese Chinese APA 7. English items render exactly as with the official style.
//
//   curl -sSL -o /tmp/apa.csl https://raw.githubusercontent.com/citation-style-language/styles/master/apa.csl
//   node scripts/csl.mjs /tmp/apa.csl
//
// Two variants: 「。」 between parts (most university APA 7 guides) and 「．」 between parts with 「。」 at the end
// (台灣護理學會), the same choice as 設定 → 中文 APA → 標點 (apa-zh.js).
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = process.argv[2];
if (!src) {
	console.error("usage: node scripts/csl.mjs <official apa.csl>");
	process.exit(1);
}
const official = readFileSync(src, "utf8");
const macros = readFileSync(join(root, "scripts", "csl", "zh-macros.xml"), "utf8");
const UPDATED = process.env.CSL_UPDATED || new Date().toISOString().slice(0, 10) + "T00:00:00+00:00";

export const VARIANTS = [
	{ file: "apa-7-zh-tw.csl", id: "apa-7-zh-tw", title: "APA 7 中英混排（臺灣，ZotMax）", short: "APA 7 中英混排", sep: "。" },
	{ file: "apa-7-zh-tw-twna.csl", id: "apa-7-zh-tw-twna", title: "APA 7 中英混排（臺灣護理學會，ZotMax）", short: "APA 7 中英混排（護理學會）", sep: "．" },
];

function build(v) {
	let s = official;
	let rep = (from, to) => {
		let n = s.split(from).length - 1;
		if (n !== 1) throw new Error(`expected one ${JSON.stringify(from.slice(0, 70))}, found ${n}`);
		s = s.replace(from, () => to);
	};
	rep(/<!-- This file was generated by the Style Variant Builder[^\n]*-->\n/.exec(s)[0],
		"  <!-- ZotMax：以 Zotero 官方「APA Style 7th edition」（CC BY-SA 3.0）為基礎，加上中文文獻的中文 APA 7 寫法（CSL-M 的 layout locale）。英文文獻的輸出與官方樣式相同。由 scripts/csl.mjs 產生。 -->\n");
	rep('<style xmlns="http://purl.org/net/xbiblio/csl" class="in-text" demote-non-dropping-particle="never"',
		// English items always in English, whatever the document language; Chinese names by stroke count (ICU zh-TW)
		'<style xmlns="http://purl.org/net/xbiblio/csl" class="in-text" default-locale="en-US" default-locale-sort="zh-TW" demote-non-dropping-particle="never"');
	rep("    <title>APA Style 7th edition</title>\n    <title-short>Publication Manual of the American Psychological Association, with Bluebook</title-short>\n    <id>http://www.zotero.org/styles/apa</id>\n    <link href=\"http://www.zotero.org/styles/apa\" rel=\"self\"/>\n    <link href=\"http://www.zotero.org/styles/apa-6th-edition\" rel=\"template\"/>\n",
		`    <title>${v.title}</title>\n    <title-short>${v.short}</title-short>\n    <id>https://bobyu89.github.io/ZotMax/styles/${v.id}</id>\n    <link href="https://bobyu89.github.io/ZotMax/styles/${v.file}" rel="self"/>\n    <link href="http://www.zotero.org/styles/apa" rel="template"/>\n    <link href="https://github.com/bobyu89/ZotMax#word-的中文-apa-引用" rel="documentation"/>\n`);
	rep("    <contributor>\n      <name>Jay Pfaffman</name>",
		"    <contributor>\n      <name>ZotMax</name>\n      <uri>https://github.com/bobyu89/ZotMax</uri>\n    </contributor>\n    <contributor>\n      <name>Jay Pfaffman</name>");
	rep(/    <summary>[^<]*<\/summary>\n/.exec(s)[0],
		"    <summary>APA 7 author-date; Chinese-language items (language zh, zh-TW) follow Taiwanese Chinese APA 7: full names, 、 between authors, 等 for et al., （年）, " + v.sep + " between parts, Chinese references first by stroke count.</summary>\n");
	rep(/<updated>[^<]*<\/updated>/.exec(s)[0], `<updated>${UPDATED}</updated>`);
	rep('  <locale xml:lang="en">\n',
		'  <locale xml:lang="zh">\n    <terms>\n      <term name="et-al">等</term>\n      <term form="short" name="editor">\n        <single>主編</single>\n        <multiple>主編</multiple>\n      </term>\n      <term form="short" name="translator">\n        <single>譯</single>\n        <multiple>譯</multiple>\n      </term>\n      <term form="short" name="page">\n        <single>頁</single>\n        <multiple>頁</multiple>\n      </term>\n    </terms>\n  </locale>\n  <locale xml:lang="en">\n');
	let zh = v.sep === "。" ? macros : macros.replace(/delimiter="。"/g, `delimiter="${v.sep}"`);
	rep("  <!-- Citation -->\n", zh + "  <!-- Citation -->\n");
	rep('    <layout delimiter="; " prefix="(" suffix=")">\n      <group delimiter=", ">\n        <text macro="author-short"/>',
		'    <layout delimiter="; " locale="zh" prefix="(" suffix=")">\n      <group delimiter="，">\n        <text macro="zh-names-short"/>\n        <text macro="zh-year"/>\n        <group delimiter=" ">\n          <label form="short" variable="locator"/>\n          <text variable="locator"/>\n        </group>\n      </group>\n    </layout>\n    <layout delimiter="; " prefix="(" suffix=")">\n      <group delimiter=", ">\n        <text macro="author-short"/>');
	rep('    <sort>\n      <key macro="author-sort"/>\n      <key macro="date-sort-group"/>',
		'    <sort>\n      <key macro="zh-first"/>\n      <key macro="author-sort"/>\n      <key macro="date-sort-group"/>');
	rep('    <layout>\n      <choose>\n        <if match="any" variable="archive archive-place container-title DOI number publisher references URL">',
		'    <layout locale="zh">\n      <text macro="zh-bibliography"/>\n    </layout>\n    <layout>\n      <choose>\n        <if match="any" variable="archive archive-place container-title DOI number publisher references URL">');
	return s;
}

for (let v of VARIANTS) {
	let out = build(v);
	for (let dir of [join(root, "content", "styles"), join(root, "site", "styles")]) writeFileSync(join(dir, v.file), out);
	console.log(`Wrote ${v.file} (${out.length} chars)`);
}
